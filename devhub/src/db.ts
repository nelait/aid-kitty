export type Param = string | number | null;

/** Something you can run queries on: the database, or an open transaction. */
export interface Queryable {
  all<T = Record<string, unknown>>(sql: string, ...params: Param[]): Promise<T[]>;
  get<T = Record<string, unknown>>(sql: string, ...params: Param[]): Promise<T | undefined>;
  run(sql: string, ...params: Param[]): Promise<{ changes: number }>;
}

export interface Db extends Queryable {
  dialect: "sqlite" | "postgres";
  /**
   * Run `fn` in a transaction. Inside it, use only the `q` it is given: on SQLite the
   * database waits for the transaction to finish, so calling `db` there would deadlock.
   */
  tx<T>(fn: (q: Queryable) => Promise<T>): Promise<T>;
  exec(sql: string): Promise<void>;
  close(): Promise<void>;
}

