const NOW_SQLITE = "(strftime('%Y-%m-%dT%H:%M:%fZ','now'))";
const NOW_PG = `(to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"'))`;

/** One schema, two dialects. Timestamps are ISO-8601 UTC strings in both. */
function schema(d: "sqlite" | "postgres"): string {
  const pk = d === "sqlite" ? "INTEGER PRIMARY KEY" : "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY";
  const now = d === "sqlite" ? NOW_SQLITE : NOW_PG;
  return `
CREATE TABLE IF NOT EXISTS teams (
  id ${pk},
  name TEXT NOT NULL UNIQUE,
  cost_center TEXT,
  monthly_pool_cents INTEGER,
  member_default_cents INTEGER,
  scim_external_id TEXT
);
CREATE TABLE IF NOT EXISTS users (
  id ${pk},
  email TEXT NOT NULL UNIQUE,
  name TEXT,
  team_id INTEGER REFERENCES teams(id),
  role TEXT NOT NULL DEFAULT 'member' CHECK (role IN ('member','manager','admin')),
  status TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active','disabled')),
  oidc_sub TEXT UNIQUE,
  claude_user_id TEXT UNIQUE,
  github_login TEXT UNIQUE,
  monthly_budget_cents INTEGER,
  created_at TEXT NOT NULL DEFAULT ${now},
  scim_external_id TEXT,
  deleted_at TEXT,
  ssh_public_key TEXT
);
CREATE TABLE IF NOT EXISTS spend (
  period TEXT NOT NULL,
  user_id INTEGER NOT NULL REFERENCES users(id),
  tool TEXT NOT NULL,
  cents INTEGER NOT NULL,
  synced_at TEXT NOT NULL,
  PRIMARY KEY (period, user_id, tool)
);
CREATE TABLE IF NOT EXISTS unmatched_spend (
  period TEXT NOT NULL,
  tool TEXT NOT NULL,
  external_id TEXT NOT NULL,
  cents INTEGER NOT NULL,
  synced_at TEXT NOT NULL,
  PRIMARY KEY (period, tool, external_id)
);
CREATE TABLE IF NOT EXISTS raise_requests (
  id ${pk},
  user_id INTEGER NOT NULL REFERENCES users(id),
  period TEXT NOT NULL,
  amount_cents INTEGER NOT NULL CHECK (amount_cents > 0),
  reason TEXT NOT NULL,
  status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','approved','denied')),
  decided_by INTEGER REFERENCES users(id),
  decision_note TEXT,
  decided_at TEXT,
  created_at TEXT NOT NULL DEFAULT ${now}
);
CREATE TABLE IF NOT EXISTS claude_caps (
  user_id INTEGER PRIMARY KEY REFERENCES users(id),
  period TEXT NOT NULL,
  cents INTEGER NOT NULL,
  pushed_at TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS sync_runs (
  id ${pk},
  ts TEXT NOT NULL,
  connector TEXT NOT NULL,
  ok INTEGER NOT NULL,
  message TEXT
);
CREATE TABLE IF NOT EXISTS web_sessions (
  token_hash TEXT PRIMARY KEY,
  user_id INTEGER NOT NULL REFERENCES users(id),
  csrf TEXT NOT NULL,
  expires_at TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS budget_alerts (
  user_id INTEGER NOT NULL REFERENCES users(id),
  period TEXT NOT NULL,
  level TEXT NOT NULL CHECK (level IN ('warning','exhausted')),
  sent_at TEXT NOT NULL,
  PRIMARY KEY (user_id, period, level)
);
CREATE TABLE IF NOT EXISTS workspace_templates (
  id ${pk},
  name TEXT NOT NULL UNIQUE,
  provider TEXT NOT NULL,
  config TEXT NOT NULL,
  hourly_usd_e4 INTEGER NOT NULL,
  storage_gb_month_cents INTEGER NOT NULL,
  stop_after_hours INTEGER NOT NULL,
  enabled INTEGER NOT NULL DEFAULT 1,
  idle_minutes INTEGER NOT NULL DEFAULT 30,
  setup_script TEXT NOT NULL DEFAULT ''
);
CREATE TABLE IF NOT EXISTS workspaces (
  id ${pk},
  user_id INTEGER NOT NULL REFERENCES users(id),
  template_id INTEGER NOT NULL REFERENCES workspace_templates(id),
  name TEXT NOT NULL,
  provider TEXT NOT NULL,
  machine_id TEXT,
  state TEXT NOT NULL,
  detail TEXT,
  disk_gb INTEGER NOT NULL,
  hourly_usd_e4 INTEGER NOT NULL,
  storage_gb_month_cents INTEGER NOT NULL,
  stop_at TEXT,
  created_at TEXT NOT NULL,
  terminated_at TEXT,
  idle_minutes INTEGER NOT NULL DEFAULT 0,
  last_active_at TEXT,
  last_heartbeat_at TEXT,
  agent_token_hash TEXT,
  budget_stop_at TEXT,
  setup_status TEXT
);
CREATE UNIQUE INDEX IF NOT EXISTS workspaces_agent_token ON workspaces (agent_token_hash);
CREATE TABLE IF NOT EXISTS workspace_runs (
  id ${pk},
  workspace_id INTEGER NOT NULL REFERENCES workspaces(id),
  user_id INTEGER NOT NULL REFERENCES users(id),
  hourly_usd_e4 INTEGER NOT NULL,
  started_at TEXT NOT NULL,
  stopped_at TEXT
);
CREATE TABLE IF NOT EXISTS output_metrics (
  period TEXT NOT NULL,
  subject TEXT NOT NULL,
  metric TEXT NOT NULL,
  value INTEGER NOT NULL,
  synced_at TEXT NOT NULL,
  PRIMARY KEY (period, subject, metric)
);
CREATE TABLE IF NOT EXISTS policies (
  scope TEXT PRIMARY KEY,
  doc TEXT NOT NULL,
  updated_at TEXT NOT NULL,
  updated_by TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS settings (
  key TEXT PRIMARY KEY,
  value TEXT NOT NULL,
  updated_at TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS audit (
  id ${pk},
  ts TEXT NOT NULL DEFAULT ${now},
  actor TEXT NOT NULL,
  action TEXT NOT NULL,
  detail TEXT
);
CREATE INDEX IF NOT EXISTS spend_user_period ON spend (user_id, period);
CREATE INDEX IF NOT EXISTS raise_requests_user ON raise_requests (user_id, status)`;
}

// ---------------------------------------------------------------- SQLite

/** Runs async work one item at a time, in arrival order. */
class Mutex {
  private tail: Promise<unknown> = Promise.resolve();
  run<T>(fn: () => Promise<T> | T): Promise<T> {
    const result = this.tail.then(fn);
    this.tail = result.catch(() => undefined);
    return result;
  }
}

/**
 * node:sqlite is synchronous and has one connection. A transaction spans awaits, so other
 * requests could otherwise slip statements into it; every call goes through a FIFO lock,
 * and a transaction holds the lock until it commits.
 */
class SqliteDb implements Db {
  dialect = "sqlite" as const;
  private lock = new Mutex();
  private direct: Queryable;

  constructor(private sqlite: DatabaseSync) {
    const s = sqlite;
    this.direct = {
      all: async <T>(sql: string, ...p: Param[]) => s.prepare(sql).all(...p) as T[],
      get: async <T>(sql: string, ...p: Param[]) => s.prepare(sql).get(...p) as T | undefined,
      run: async (sql: string, ...p: Param[]) => ({ changes: Number(s.prepare(sql).run(...p).changes) }),
    };
  }

  all<T>(sql: string, ...p: Param[]) {
    return this.lock.run(() => this.direct.all<T>(sql, ...p));
  }
  get<T>(sql: string, ...p: Param[]) {
    return this.lock.run(() => this.direct.get<T>(sql, ...p));
  }
  run(sql: string, ...p: Param[]) {
    return this.lock.run(() => this.direct.run(sql, ...p));
  }
  exec(sql: string) {
    return this.lock.run(() => this.sqlite.exec(sql));
  }
  tx<T>(fn: (q: Queryable) => Promise<T>): Promise<T> {
    return this.lock.run(async () => {
      this.sqlite.exec("BEGIN IMMEDIATE");
      try {
        const out = await fn(this.direct);
        this.sqlite.exec("COMMIT");
        return out;
      } catch (e) {
        this.sqlite.exec("ROLLBACK");
        throw e;
      }
    });
  }
  async close() {
    await this.lock.run(() => this.sqlite.close());
  }
}

async function openSqlite(path: string): Promise<Db> {
  const s = new DatabaseSync(path);
  s.exec("PRAGMA journal_mode = WAL; PRAGMA foreign_keys = ON; PRAGMA busy_timeout = 5000;");
  // Additive migrations for databases created by earlier versions, before the indexes that use them.
  const addColumn = (table: string, column: string, type: string) => {
    const cols = s.prepare(`PRAGMA table_info(${table})`).all() as { name: string }[];
    if (cols.length && !cols.some((c) => c.name === column)) s.exec(`ALTER TABLE ${table} ADD COLUMN ${column} ${type}`);
  };
  addColumn("users", "scim_external_id", "TEXT");
  addColumn("users", "deleted_at", "TEXT");
  addColumn("teams", "scim_external_id", "TEXT");
  addColumn("users", "ssh_public_key", "TEXT");
  addColumn("workspace_templates", "idle_minutes", "INTEGER NOT NULL DEFAULT 30");
  addColumn("workspaces", "idle_minutes", "INTEGER NOT NULL DEFAULT 0");
  addColumn("workspaces", "last_active_at", "TEXT");
  addColumn("workspaces", "last_heartbeat_at", "TEXT");
  addColumn("workspaces", "agent_token_hash", "TEXT");
  addColumn("workspaces", "budget_stop_at", "TEXT");
  addColumn("workspaces", "setup_status", "TEXT");
  addColumn("workspace_templates", "setup_script", "TEXT NOT NULL DEFAULT ''");
  s.exec(schema("sqlite"));
  // Earlier versions matched emails and GitHub logins case-insensitively in SQL; now the
  // app stores them lowercase so the same queries work on Postgres.
  s.exec("UPDATE users SET email = lower(email), github_login = lower(github_login) WHERE email != lower(email) OR github_login != lower(github_login)");
  return new SqliteDb(s);
}

// ---------------------------------------------------------------- Postgres

// COUNT and SUM come back as int8/numeric, which node-postgres returns as strings.
// Dev Hub's amounts are cents well inside Number's safe range, so read them as numbers.
pg.types.setTypeParser(pg.types.builtins.INT8, (v) => Number(v));
pg.types.setTypeParser(pg.types.builtins.NUMERIC, (v) => Number(v));

/** `?` placeholders → `$1, $2, …`. Dev Hub's SQL never contains a literal `?`. */
const toPg = (sql: string) => {
  let i = 0;
  return sql.replace(/\?/g, () => `$${++i}`);
};

const pgQueryable = (c: pg.Pool | pg.PoolClient): Queryable => ({
  all: async <T>(sql: string, ...p: Param[]) => (await c.query(toPg(sql), p)).rows as T[],
  get: async <T>(sql: string, ...p: Param[]) => (await c.query(toPg(sql), p)).rows[0] as T | undefined,
  run: async (sql: string, ...p: Param[]) => ({ changes: (await c.query(toPg(sql), p)).rowCount ?? 0 }),
});

class PostgresDb implements Db {
  dialect = "postgres" as const;
  private q: Queryable;

  constructor(private pool: pg.Pool) {
    this.q = pgQueryable(pool);
  }

  all<T>(sql: string, ...p: Param[]) {
    return this.q.all<T>(sql, ...p);
  }
  get<T>(sql: string, ...p: Param[]) {
    return this.q.get<T>(sql, ...p);
  }
  run(sql: string, ...p: Param[]) {
    return this.q.run(sql, ...p);
  }
  async exec(sql: string) {
    await this.pool.query(sql);
  }
  async tx<T>(fn: (q: Queryable) => Promise<T>): Promise<T> {
    const client = await this.pool.connect();
    try {
      await client.query("BEGIN");
      const out = await fn(pgQueryable(client));
      await client.query("COMMIT");
      return out;
    } catch (e) {
      await client.query("ROLLBACK").catch(() => undefined);
      throw e;
    } finally {
      client.release();
    }
  }
  close() {
    return this.pool.end();
  }
}

async function openPostgres(url: string): Promise<Db> {
  const pool = new pg.Pool({ connectionString: url, max: 10 });
  pool.on("error", (e) => console.error("postgres pool error:", e.message));
  const db = new PostgresDb(pool);
  // Replicas starting together take turns creating the schema. Future column additions
  // go after it as `ALTER TABLE ... ADD COLUMN IF NOT EXISTS`.
  await db.tx(async (q) => {
    await q.run("SELECT pg_advisory_xact_lock(4242001)");
    for (const stmt of schema("postgres").split(";").map((x) => x.trim()).filter(Boolean)) await q.run(stmt);
    // Columns added after a table first shipped.
    await q.run("ALTER TABLE users ADD COLUMN IF NOT EXISTS ssh_public_key TEXT");
    await q.run("ALTER TABLE workspace_templates ADD COLUMN IF NOT EXISTS idle_minutes INTEGER NOT NULL DEFAULT 30");
    await q.run("ALTER TABLE workspaces ADD COLUMN IF NOT EXISTS idle_minutes INTEGER NOT NULL DEFAULT 0");
    await q.run("ALTER TABLE workspaces ADD COLUMN IF NOT EXISTS last_active_at TEXT");
    await q.run("ALTER TABLE workspaces ADD COLUMN IF NOT EXISTS last_heartbeat_at TEXT");
    await q.run("ALTER TABLE workspaces ADD COLUMN IF NOT EXISTS agent_token_hash TEXT");
    await q.run("ALTER TABLE workspaces ADD COLUMN IF NOT EXISTS budget_stop_at TEXT");
    await q.run("ALTER TABLE workspaces ADD COLUMN IF NOT EXISTS setup_status TEXT");
    await q.run("ALTER TABLE workspace_templates ADD COLUMN IF NOT EXISTS setup_script TEXT NOT NULL DEFAULT ''");
  });
  return db;
}

