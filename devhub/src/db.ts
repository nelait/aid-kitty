/** A `postgres://` / `postgresql://` URL opens Postgres; anything else is a SQLite file path. */
export function openDb(location: string): Promise<Db> {
  return /^postgres(ql)?:\/\//.test(location) ? openPostgres(location) : openSqlite(location);
}

export function isUniqueViolation(e: unknown): boolean {
  const err = e as { code?: string; message?: string };
  return err?.code === "23505" || /UNIQUE constraint failed/.test(String(err?.message));
}

export async function audit(q: Queryable, actor: string, action: string, detail: unknown): Promise<void> {
  await q.run("INSERT INTO audit (actor, action, detail) VALUES (?, ?, ?)", actor, action, JSON.stringify(detail));
}

export const nowIso = (): string => new Date().toISOString();

export function getUser(q: Queryable, id: number): Promise<User | undefined> {
  return q.get<User>("SELECT * FROM users WHERE id = ?", id);
}

export function getUserByEmail(q: Queryable, email: string): Promise<User | undefined> {
  return q.get<User>("SELECT * FROM users WHERE email = ?", email.toLowerCase());
}

export async function getTeam(q: Queryable, id: number | null): Promise<Team | undefined> {
  if (id === null) return undefined;
  return q.get<Team>("SELECT * FROM teams WHERE id = ?", id);
}

/** Insert and return the new row's id (both dialects support RETURNING). */
export async function insertId(q: Queryable, sql: string, ...params: Param[]): Promise<number> {
  const row = await q.get<{ id: number }>(`${sql} RETURNING id`, ...params);
  return Number(row!.id);
}
